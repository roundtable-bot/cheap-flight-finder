#!/usr/bin/env python3
"""Build distributables for every skill in skills/.

  python3 tools/build.py          # write claude-web/<skill>.md and dist/<skill>.zip
  python3 tools/build.py --check  # fail if claude-web/ is out of date (used in CI)

claude-web/<skill>.md is SKILL.md as one paste-able page (no frontmatter, bundled
scripts appended), for assistants that can't install a skill folder.
"""
import pathlib
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
LANG = {".py": "python", ".js": "js", ".sh": "bash"}
PATH_NOTE = ("The script paths are relative to this skill's folder; "
             "use the full path if you're running from somewhere else.")
PASTE_NOTE = ("The scripts are at the end of these instructions. Save each one under its "
              "file name and run it with your code execution tool. On Claude.ai, the code "
              "sandbox needs internet access to these sites (Settings → Capabilities, network "
              "access for code execution). If it can't connect, the scripts fail with a network "
              "error; tell the user that and give the links.")


def paste_version(skill):
    text = (skill / "SKILL.md").read_text()
    _, front, body = text.split("---", 2)
    desc = next(l.split(":", 1)[1].strip() for l in front.splitlines() if l.startswith("description:"))
    if (skill / "scripts").exists() and PATH_NOTE not in body:
        sys.exit(f"{skill.name}/SKILL.md: missing the script path note that the paste version replaces")
    body = body.strip().replace(PATH_NOTE, PASTE_NOTE).replace("scripts/", "")
    title, rest = body.split("\n", 1)
    out = [f"<!-- Generated by tools/build.py from skills/{skill.name}/. Do not edit. -->", "", title, "",
           f"Follow these instructions when I ask you to: {desc}", rest, ""]
    for f in sorted(p for p in (skill / "scripts").glob("*") if p.is_file() and p.suffix != ".pyc"):
        out += [f"## Appendix: {f.name}", "", f"```{LANG.get(f.suffix, '')}", f.read_text().rstrip(), "```", ""]
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    stale = []
    for skill in sorted(p for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").exists()):
        target = ROOT / "claude-web" / f"{skill.name}.md"
        content = paste_version(skill)
        if check:
            if not target.exists() or target.read_text() != content:
                stale.append(str(target.relative_to(ROOT)))
            continue
        target.parent.mkdir(exist_ok=True)
        target.write_text(content)
        (ROOT / "dist").mkdir(exist_ok=True)
        with zipfile.ZipFile(ROOT / "dist" / f"{skill.name}.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(skill.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    z.write(f, f.relative_to(skill.parent))
        print(f"built claude-web/{skill.name}.md and dist/{skill.name}.zip")
    if stale:
        sys.exit("out of date, run `python3 tools/build.py`: " + ", ".join(stale))


if __name__ == "__main__":
    main()
